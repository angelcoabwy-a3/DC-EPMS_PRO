"""
scripts/build_site_model_v2.py -- DC-EPMS-068.

Generate config/site_model_v2.yml and config/telemetry_mapping_v2.yml from config/site_model.yml (legacy)
and config/power_plant.yml (closed Phase 1 design), then validate it.

    python scripts/build_site_model_v2.py           write + validate
    python scripts/build_site_model_v2.py --check   fail if the committed
                                                    file is stale or invalid
Exit code 0 = OK, 1 = validation problems or stale file.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.site_model_v2 import build, telemetry_mapping, validate  # noqa: E402

LEGACY = ROOT / "config" / "site_model.yml"
PLANT = ROOT / "config" / "power_plant.yml"
OUT = ROOT / "config" / "site_model_v2.yml"
TELEMETRY_OUT = ROOT / "config" / "telemetry_mapping_v2.yml"

HEADER = (
    "# config/site_model_v2.yml -- GENERATED by scripts/build_site_model_v2.py\n"
    "# DO NOT EDIT. Inputs: config/site_model.yml (legacy) +\n"
    "# config/power_plant.yml (closed Phase 1 power design). DC-EPMS-068.\n"
    "# Runtime still loads config/site_model.yml; see\n"
    "# docs/design/DC-EPMS-068_MIGRATION.md for the consumer inventory.\n"
)


def render() -> tuple[dict[pathlib.Path, str], list[str]]:
    legacy = yaml.safe_load(LEGACY.read_text(encoding="utf-8"))
    plant = yaml.safe_load(PLANT.read_text(encoding="utf-8"))
    model = build(legacy, plant)
    dump = lambda data: yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)  # noqa: E731
    files = {
        OUT: HEADER + dump(model),
        TELEMETRY_OUT: HEADER.replace("site_model_v2.yml", "telemetry_mapping_v2.yml", 1)
        + dump(telemetry_mapping(model, plant)),
    }
    return files, validate(model, plant)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files, problems = render()
    for problem in problems:
        print(f"[FAIL] {problem}")
    for path, text in files.items():
        name = path.relative_to(ROOT)
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != text:
                print(f"[FAIL] {name} is stale: run scripts/build_site_model_v2.py")
                return 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"[OK] wrote {name}")
    if problems:
        return 1
    print("[OK] site_model_v2 consistent with the closed design")
    return 0


if __name__ == "__main__":
    sys.exit(main())
