"""
backend/loto_auditor_report_renderer.py
=========================================
Pure-function markdown renderer for LotoAuditReport (Batch 4.D).

Design principles:
  - Pure function: render_audit_report_markdown(report) -> str
  - No I/O, no state, no globals
  - Deterministic output for same input
  - Markdown is universal: HMI uses marked.js, future PDF export uses
    pandoc/reportlab (V10), and CETs can copy-paste to email/Slack
  - Per-pillar sections always rendered (even NOT_APPLICABLE) for
    audit completeness and reviewer expectation consistency
  - Status banner at top per ADR-006 Deterministic Sandbox
"""

from __future__ import annotations

from loto_auditor_models import (
    AuditStatus,
    LotoAuditReport,
    PillarOutcome,
)

# =============================================================================
#  Outcome marker mapping (text-based, no emoji to avoid encoding pitfalls)
# =============================================================================

OUTCOME_MARKER: dict[PillarOutcome, str] = {
    PillarOutcome.PASS: "[PASS]",
    PillarOutcome.WARN: "[WARN]",
    PillarOutcome.HARD_FAIL: "[HARD FAIL]",
    PillarOutcome.NOT_APPLICABLE: "[N/A]",
}


def _marker(outcome: PillarOutcome) -> str:
    return OUTCOME_MARKER.get(outcome, f"[{outcome.value}]")


# =============================================================================
#  Section renderers (each returns a markdown string)
# =============================================================================


def _render_header(report: LotoAuditReport) -> str:
    status_text = report.status.value.upper().replace("_", " ")
    banner = ""
    if report.status == AuditStatus.PENDING_APPROVAL:
        banner = (
            "\n> **STATUS: PENDING APPROVAL** "
            "(per ADR-006 Deterministic Sandbox: AI drafts, CET approves)\n"
        )
    elif report.status == AuditStatus.APPROVED:
        banner = f"\n> **STATUS: APPROVED** by {report.approver_cet or 'unknown'}\n"
    elif report.status == AuditStatus.REJECTED:
        reason = report.rejection_reason or "no reason provided"
        banner = f"\n> **STATUS: REJECTED** Reason: {reason}\n"

    return (
        f"# LOTO Audit Report `{report.audit_id}`\n"
        f"{banner}\n"
        f"**Procedure**: `{report.procedure_id}`  \n"
        f"**Target component**: `{report.target_component_id}`  \n"
        f"**CET on duty**: {report.cet_on_duty}  \n"
        f"**Facility**: {report.facility}  \n"
        f"**Audited at**: {report.timestamp.isoformat()}  \n"
        f"**Snapshot timestamp**: {report.as_of_timestamp.isoformat()}  \n"
    )


def _render_executive_summary(report: LotoAuditReport) -> str:
    return (
        "\n## Executive Summary\n"
        f"\n**Overall outcome**: {_marker(report.overall_outcome)} "
        f"`{report.overall_outcome.value}`\n\n"
        "| Outcome | Count |\n"
        "|---|---|\n"
        f"| HARD_FAIL | {report.hard_fail_count} |\n"
        f"| WARN | {report.warn_count} |\n"
        f"| PASS | {report.pass_count} |\n"
        f"| NOT_APPLICABLE | {report.not_applicable_count} |\n"
        f"\nDecision time: **{report.decision_time_ms}ms**  \n"
        f"API version: {report.api_version}\n"
    )


def _render_llm_summary(report: LotoAuditReport) -> str:
    if not report.llm_summary:
        if report.llm_synthesis_status == "skipped":
            return ""
        return (
            "\n## LLM Executive Summary\n\n"
            f"_LLM synthesis status: {report.llm_synthesis_status}. "
            "No summary available._\n"
        )
    return (
        "\n## LLM Executive Summary\n\n"
        f"_(Generated by local LM Studio, status: {report.llm_synthesis_status})_\n\n"
        f"{report.llm_summary}\n"
    )


def _render_pillar_1(report: LotoAuditReport) -> str:
    p = report.impact_radius
    affected_str = (
        ", ".join(f"`{c}`" for c in p.affected_components[:10])
        if p.affected_components
        else "_(none)_"
    )
    if len(p.affected_components) > 10:
        affected_str += f" _(and {len(p.affected_components) - 10} more)_"

    cooling_str = (
        ", ".join(f"`{c}`" for c in p.cooling_chain_affected[:5])
        if p.cooling_chain_affected
        else "_(none)_"
    )

    notes_block = ""
    if p.notes:
        notes_block = "\n**Notes**:\n" + "\n".join(f"- {n}" for n in p.notes) + "\n"

    return (
        f"\n## Pillar 1: Topology Impact Radius — {_marker(p.outcome)}\n"
        f"\n- **Blast radius**: {p.blast_radius_racks} racks, "
        f"{p.blast_radius_kw:.2f} kW\n"
        f"- **Immediate downstream**: {len(p.immediate_loads)} components\n"
        f"- **Transitive downstream**: {len(p.transitive_loads)} components\n"
        f"- **Affected components**: {affected_str}\n"
        f"- **Cooling chain affected**: {cooling_str}\n"
        f"- **GraphRAG topology consistent**: "
        f"{'yes' if p.graphrag_consistency_check else 'no (see notes)'}\n"
        f"{notes_block}"
    )


def _render_pillar_2(report: LotoAuditReport) -> str:
    p = report.redundancy
    spofs_str = (
        "\n".join(f"- {spof}" for spof in p.single_points_of_failure)
        if p.single_points_of_failure
        else "_(none detected)_"
    )

    fail_block = ""
    if p.hard_fail_reasons:
        fail_block = (
            "\n**Hard fail reasons**:\n" + "\n".join(f"- {r}" for r in p.hard_fail_reasons) + "\n"
        )

    return (
        f"\n## Pillar 2: 2N Redundancy Survival — {_marker(p.outcome)}\n"
        f"\n- **Target path**: {p.target_path or 'unknown / not 2N protected'}\n"
        f"- **Path A state**: `{p.path_a_state}`\n"
        f"- **Path B state**: `{p.path_b_state}`\n"
        f"- **SHI pre-LOTO**: {p.shi_pre_loto:.3f}\n"
        f"- **SHI post-LOTO**: {p.shi_post_loto:.3f}\n"
        f"- **SHI threshold**: {p.shi_threshold:.3f}\n"
        f"- **Overlapping maintenance**: "
        f"{'YES (alarm)' if p.overlapping_maintenance else 'no'}\n"
        f"- **Single points of failure**:\n{spofs_str}\n"
        f"{fail_block}"
    )


def _render_pillar_3(report: LotoAuditReport) -> str:
    p = report.capacitor_discharge
    notes_block = ""
    if p.notes:
        notes_block = "\n**Notes**:\n" + "\n".join(f"- {n}" for n in p.notes) + "\n"

    return (
        f"\n## Pillar 3: Capacitor Discharge (NEC 460.6) — {_marker(p.outcome)}\n"
        f"\n- **Discharge required**: {p.required}\n"
        f"- **Reason**: {p.required_reason or '_(not required)_'}\n"
        f"- **Found in procedure**: {p.found_in_procedure}\n"
        f"- **Wait duration**: {p.wait_duration_s}s "
        f"(minimum required {p.minimum_required_s}s)\n"
        f"- **CAT IV voltmeter verification**: {p.voltmeter_verification}\n"
        f"- **Target threshold voltage**: {p.target_threshold_v} V\n"
        f"- **Citation**: {p.citation}\n"
        f"{notes_block}"
    )


def _render_pillar_4(report: LotoAuditReport) -> str:
    p = report.witness_gate
    steps_str = (
        ", ".join(f"`{s}`" for s in p.witness_steps)
        if p.witness_steps
        else "_(no witness steps in procedure)_"
    )
    notes_block = ""
    if p.notes:
        notes_block = "\n**Notes**:\n" + "\n".join(f"- {n}" for n in p.notes) + "\n"

    return (
        f"\n## Pillar 4: Witness Gate (LOTO Level 3+) — {_marker(p.outcome)}\n"
        f"\n- **LOTO Level**: {p.loto_level.value}\n"
        f"- **Level rationale**: {p.level_rationale}\n"
        f"- **Witness required**: {p.witness_required}\n"
        f"- **Witness steps**: {steps_str}\n"
        f"- **Identity collision protection**: "
        f"{p.identity_collision_protected}\n"
        f"{notes_block}"
    )


def _render_pillar_5(report: LotoAuditReport) -> str:
    p = report.sequential_order
    phases_str = (
        " -> ".join(phase.value for phase in p.phases_detected)
        if p.phases_detected
        else "_(no steps)_"
    )
    warnings_block = ""
    if p.warnings:
        warnings_block = "\n**Warnings**:\n" + "\n".join(f"- {w}" for w in p.warnings) + "\n"
    fail_block = ""
    if p.hard_fail_reasons:
        fail_block = (
            "\n**Hard fail reasons**:\n" + "\n".join(f"- {r}" for r in p.hard_fail_reasons) + "\n"
        )

    return (
        f"\n## Pillar 5: Hybrid Sequential Order — {_marker(p.outcome)}\n"
        f"\n- **Phases detected (in step order)**: {phases_str}\n"
        f"- **Order correct (Electrical -> Hydraulic -> Purge)**: "
        f"{p.phases_in_correct_order}\n"
        f"- **Purge required (cooling involved)**: {p.purge_required}\n"
        f"- **Purge step present**: {p.purge_present}\n"
        f"{warnings_block}{fail_block}"
    )


def _render_pillar_6(report: LotoAuditReport) -> str:
    p = report.ppe_category
    specified_str = (
        f"CAT {p.procedure_specified_category.value}"
        if p.procedure_specified_category is not None
        else "_(not specified)_"
    )
    citations_str = ", ".join(p.citations)
    warnings_block = ""
    if p.warnings:
        warnings_block = "\n**Warnings**:\n" + "\n".join(f"- {w}" for w in p.warnings) + "\n"
    fail_block = ""
    if p.hard_fail_reasons:
        fail_block = (
            "\n**Hard fail reasons**:\n" + "\n".join(f"- {r}" for r in p.hard_fail_reasons) + "\n"
        )

    incident_str = (
        f"{p.incident_energy_cal_cm2:.2f}"
        if p.incident_energy_cal_cm2 is not None
        else "_(not calculated, IEEE 1584 deferred per ADR-009 V10)_"
    )

    return (
        f"\n## Pillar 6: PPE Category (NFPA 70E) — {_marker(p.outcome)}\n"
        f"\n- **Voltage nominal**: {p.voltage_nominal:.0f} V\n"
        f"- **Computed required category**: CAT {p.computed_category.value}\n"
        f"- **Procedure-specified category**: {specified_str}\n"
        f"- **Incident energy (cal/cm2)**: {incident_str}\n"
        f"- **Citations**: {citations_str}\n"
        f"{warnings_block}{fail_block}"
    )


def _render_provenance(report: LotoAuditReport) -> str:
    if not report.sources_consulted:
        return ""
    rows = "\n".join(
        f"| `{src}` | {status} |" for src, status in sorted(report.sources_consulted.items())
    )
    return f"\n## Provenance Trace\n\n| Source | Status |\n|---|---|\n{rows}\n"


def _render_standards(report: LotoAuditReport) -> str:
    if not report.standards_cited:
        return ""
    items = "\n".join(f"- {std}" for std in report.standards_cited)
    return f"\n## Standards Cited\n\n{items}\n"


def _render_footer(report: LotoAuditReport) -> str:
    return (
        "\n---\n\n"
        f"_Audit generated by DC-EPMS PRO LOTO Auditor Agent v{report.api_version} "
        "in compliance with ADR-006 Deterministic Sandbox._  \n"
        f"_Audit ID: `{report.audit_id}`_\n"
    )


# =============================================================================
#  Public API
# =============================================================================


def render_audit_report_markdown(report: LotoAuditReport) -> str:
    """Render a LotoAuditReport as a complete markdown document.

    Pure function: same input always produces same output. No I/O, no
    side effects. Output is suitable for HMI rendering via marked.js,
    email/Slack copy-paste, or future PDF conversion via pandoc.
    """
    sections = [
        _render_header(report),
        _render_executive_summary(report),
        _render_llm_summary(report),
        _render_pillar_1(report),
        _render_pillar_2(report),
        _render_pillar_3(report),
        _render_pillar_4(report),
        _render_pillar_5(report),
        _render_pillar_6(report),
        _render_standards(report),
        _render_provenance(report),
        _render_footer(report),
    ]
    return "\n".join(s for s in sections if s)


__all__ = [
    "OUTCOME_MARKER",
    "render_audit_report_markdown",
]
